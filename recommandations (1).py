def get_data_pred(df, pred):
    """
    Filter a DataFrame to rows where 'category' matches the predicted category.
    """
    return df[df["category"] == pred].reset_index(drop=True)

def display_images(data_pred, top_image=5):
    """
    Select a random set of image paths (top_image count) from a filtered DataFrame
    that contains an 'img_path' column. Returns a list of image filenames with .jpg.
    """
    images = []
    for _ in range(top_image):
        # Pick a random row from data_pred
        ran = random.randint(0, len(data_pred) - 1)  # Avoid out-of-range index
        images.append(data_pred["img_path"][ran] + ".jpg")
    return images

