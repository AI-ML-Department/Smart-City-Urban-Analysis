from transformers import CLIPProcessor, CLIPModel
from PIL import Image
import matplotlib.pyplot as plt

def classify_furniture(image_path):
    """
    Classify furniture in an image using CLIP zero-shot classification.
    Returns: Dictionary of class probabilities, sorted descending by probability.
    """
    # Load pretrained CLIP model and processor
    model = CLIPModel.from_pretrained("openai/clip-vit-base-patch32")
    processor = CLIPProcessor.from_pretrained("openai/clip-vit-base-patch32")

    # Define furniture categories
    classes = [
        'chair', 'plant', 'nightstand', 'sofa', 'desk', 'dressing table',
        'painting', 'carpet', 'tv', 'lamp', 'bed', 'wardrobe', 'table',
        'vase', 'night light', 'dining table', 'mirror'
    ]

    # Load and process image
    image = Image.open(image_path).convert("RGB")
    inputs = processor(
        text=classes,
        images=image,
        return_tensors="pt",
        padding=True
    )

    # Get predictions from model
    outputs = model(**inputs)
    logits_per_image = outputs.logits_per_image
    probs = logits_per_image.softmax(dim=1).detach().numpy()

    # Map each class to its probability and sort by descending probability
    results = {cls: float(prob) for cls, prob in zip(classes, probs[0])}
    sorted_results = dict(sorted(results.items(), key=lambda item: item[1], reverse=True))
    return sorted_results

