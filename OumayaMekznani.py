# Part 3: Data Cleaning

missing_count=df.isnull().sum()
missing_percent=(df.isnull().mean()*100).round(2)
missing_summary=pd.DataFrame({
    "Missing values":missing_count,
    "Missing percentage (%)":missing_percent
})

# Check missing values
display(missing_summary.sort_values("Missing percentage (%)",ascending=False))

# Number of duplicate rows
duplicate_count=df.duplicated().sum()
print("Number of duplicated rows:",duplicate_count)

# Data without duplicate rows
df=df.drop_duplicates().copy()

df.info()

# Fill missing numbers with the median
for col in numerical:
   df[col]=df[col].fillna(df[col].median())

# Fill missing text with the most commun value
for col in numerical:
  if df[col].isnull().any():
    df[col]=df[col].fillna(df[col].mode()[0])

print ("\n Missing values after cleaning:\n")
print(df.isnull().sum())

