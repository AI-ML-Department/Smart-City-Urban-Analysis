# Part 5: Data Preprocessing

# Encode categorical columns
cleaned=pd.get_dummies(df,drop_first=True)

# Scale numerical columns between 0 and 1
for col in cleaned.select_dtypes(include="number").columns:
  minimum=cleaned[col].min()
  maximum=cleaned[col].max()
  if maximum != minimum:
    cleaned[col]=(cleaned[col] - minimum)/(maximum - minimum)

print("Numerical columns scaled successfully !")

# save as a new file
cleaned.to_csv("smart_city_cleaned.csv",index=False)
print("cleaned file saved!")

